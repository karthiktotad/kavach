/**
 * Generates supabase/seed.sql from the content pack.
 *
 *   node scripts/seed-from-pack.ts
 *
 * The pack is the source of truth for zones and shelters, so the database is
 * derived from it rather than maintained by hand. That way a pack rebuild
 * followed by a reseed keeps the server and the device agreeing — which matters
 * because the client refuses to trust a zone it does not know.
 *
 * Everything is written with `verified = false`. Rule 7: OSM-derived places
 * are not a verified claim, and a database column is exactly where someone
 * would be tempted to flip that to true without checking.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { PACK_DIR, fail, info, step } from './_lib.ts'
import type { PlacesFile, ZonesGeoJson } from '../src/lib/packTypes.ts'

/** Escape a value for a single-quoted SQL literal. */
function sql(value: unknown): string {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number') {
    return Number.isFinite(value) ? String(value) : 'null'
  }
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  // Anything else is serialised as JSON, which is explicit and cannot produce a
  // stray "[object Object]" in the generated SQL.
  const text = typeof value === 'string' ? value : (JSON.stringify(value) ?? '')
  // Doubling the quote is the only escape Postgres needs inside '...'.
  return `'${text.replace(/'/g, "''")}'`
}

function centroid(ring: readonly (readonly [number, number])[]): { lat: number; lon: number } {
  // Averaging vertices is crude but adequate: these are small hand-drawn zones
  // used only as an Open-Meteo query point, not as an authoritative location.
  let lat = 0
  let lon = 0
  for (const [x, y] of ring) {
    lon += x
    lat += y
  }
  return {
    lon: Number((lon / ring.length).toFixed(6)),
    lat: Number((lat / ring.length).toFixed(6)),
  }
}

async function main(): Promise<void> {
  step('seed-from-pack — generate supabase/seed.sql')

  const [zonesRaw, placesRaw] = await Promise.all([
    readFile(join(PACK_DIR, 'zones.geojson'), 'utf8'),
    readFile(join(PACK_DIR, 'places.json'), 'utf8'),
  ])
  const zones = JSON.parse(zonesRaw) as ZonesGeoJson
  const places = JSON.parse(placesRaw) as PlacesFile

  const lines: string[] = [
    '-- =============================================================================',
    '-- Kavach seed data — GENERATED by scripts/seed-from-pack.ts',
    '--',
    '-- Do not edit by hand: edit the content pack and re-run the script.',
    `-- Source pack: ${places.count} places, ${zones.features.length} zones`,
    '--',
    '-- Every row is written with verified = false. Rule 7: machine-extracted or',
    '-- hand-drawn data is not a verified claim until a human checks it, and the UI',
    '-- must show an unverified badge until then.',
    '-- =============================================================================',
    '',
    '-- Idempotent: re-running updates in place rather than failing.',
    '',
    'begin;',
    '',
    '-- ---------------------------------------------------------------- zones',
  ]

  for (const feature of zones.features) {
    const ring = feature.geometry.coordinates[0]!
    const centre = centroid(ring)
    lines.push(
      `insert into public.zones (id, name, lat, lon, flood_prone, geometry, note, source, verified)`,
      `values (${sql(feature.properties.id)}, ${sql(feature.properties.name)}, ` +
        `${sql(centre.lat)}, ${sql(centre.lon)}, ${sql(feature.properties.floodProne)}, ` +
        `${sql(JSON.stringify(feature.geometry))}::jsonb, ${sql(feature.properties.note)}, ` +
        `${sql(feature.properties.source)}, false)`,
      'on conflict (id) do update set',
      '  name = excluded.name, lat = excluded.lat, lon = excluded.lon,',
      '  flood_prone = excluded.flood_prone, geometry = excluded.geometry,',
      '  note = excluded.note;',
      '',
    )
  }

  lines.push('-- ------------------------------------------------------------- shelters')

  for (const place of places.places) {
    // `notes` in the pack is a plain string ("healthcare:speciality=general"),
    // not an object, so it cannot be cast straight to jsonb. Wrap it in a real
    // object and carry the provenance alongside it: if this row ever reaches a
    // screen, the UI needs to know the place came from OSM and is unverified.
    const metadata = {
      source: place.source,
      verified: place.verified,
      ...(place.notes ? { notes: place.notes } : {}),
    }

    lines.push(
      'insert into public.shelters (id, name, type, lat, lon, verified, metadata)',
      `values (${sql(place.id)}, ${sql(place.name)}, ${sql(place.type)}, ` +
        `${sql(place.lat)}, ${sql(place.lon)}, false, ${sql(metadata)}::jsonb)`,
      'on conflict (id) do update set',
      '  name = excluded.name, type = excluded.type, lat = excluded.lat, lon = excluded.lon,',
      '  metadata = excluded.metadata;',
      '',
    )
  }

  lines.push(
    'commit;',
    '',
    '-- =============================================================================',
    '-- Seeding an authority (run manually — see docs/BACKEND.md)',
    '--',
    '--   1. Sign up normally in Supabase Auth (or create a user by email).',
    '--   2. Find the user id:',
    '--        select id, email from auth.users order by created_at desc limit 5;',
    '--   3. Promote them:',
    '--        insert into public.profiles (id, role, display_name)',
    "--        values ('<USER_ID>', 'authority', 'District Control Room')",
    "--        on conflict (id) do update set role = 'authority';",
    '--',
    '-- There is deliberately no UPDATE policy on profiles, so a signed-in user',
    '-- cannot promote themselves; only this SQL can.',
    '-- =============================================================================',
    '',
  )

  const out = join(REPO_ROOT_SUPABASE(), 'seed.sql')
  await writeFile(out, lines.join('\n'), 'utf8')

  info(`wrote supabase/seed.sql — ${zones.features.length} zones, ${places.count} shelters`)
  info('all rows written with verified = false')
  info('authority user instructions are at the bottom of the file')
}

function REPO_ROOT_SUPABASE(): string {
  return join(process.cwd(), 'supabase')
}

try {
  await main()
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}
